const slug = s => (s || "").toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
const parseLinks = body => {
  const out = new Set();
  const re = /\[\[([^\]]+)\]\]/g; let m;
  while ((m = re.exec(body || ""))) out.add(m[1].trim());
  return [...out];
};

