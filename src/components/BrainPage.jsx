// ── inline markdown (bold, code, links, [[wikilinks]]) → React nodes ───────────
function renderInline(text, onOpen, C, kp) {
  const RE = /\[\[([^\]]+)\]\]|\*\*([^*]+)\*\*|\[([^\]]+)\]\(([^)]+)\)|`([^`]+)`/g;
  const out = []; let last = 0, m, i = 0;
  while ((m = RE.exec(text))) {
    if (m.index > last) out.push(text.slice(last, m.index));
    if (m[1] != null) {
      const t = m[1].trim();
      out.push(<span key={`${kp}-${i}`} onClick={() => onOpen(t)} style={{ color: C.purpleL, cursor: "pointer", borderBottom: `1px dotted ${C.purple}` }}>{t}</span>);
    } else if (m[2] != null) {
      out.push(<strong key={`${kp}-${i}`} style={{ color: C.text }}>{m[2]}</strong>);
    } else if (m[3] != null) {
      out.push(<a key={`${kp}-${i}`} href={m[4]} target="_blank" rel="noreferrer" style={{ color: C.teal }}>{m[3]}</a>);
    } else if (m[5] != null) {
      out.push(<code key={`${kp}-${i}`} style={{ background: C.bg, padding: "1px 5px", borderRadius: 4, fontSize: 12, fontFamily: "monospace" }}>{m[5]}</code>);
    }
    last = m.index + m[0].length; i++;
  }
  if (last < text.length) out.push(text.slice(last));
  return out;
}

function Markdown({ text, onOpen, C }) {
  const lines = (text || "").split("\n");
  const blocks = []; let list = null;
  const flush = () => { if (list) { blocks.push(<ul key={`ul${blocks.length}`} style={{ margin: "6px 0", paddingLeft: 20 }}>{list}</ul>); list = null; } };
  lines.forEach((ln, idx) => {
    const k = `l${idx}`;
    if (/^###\s/.test(ln)) { flush(); blocks.push(<div key={k} style={{ fontSize: 13, fontWeight: 600, color: C.text, margin: "10px 0 4px" }}>{renderInline(ln.slice(4), onOpen, C, k)}</div>); }
    else if (/^##\s/.test(ln)) { flush(); blocks.push(<div key={k} style={{ fontSize: 15, fontWeight: 700, color: C.text, margin: "12px 0 5px" }}>{renderInline(ln.slice(3), onOpen, C, k)}</div>); }
    else if (/^#\s/.test(ln)) { flush(); blocks.push(<div key={k} style={{ fontSize: 17, fontWeight: 700, color: C.text, margin: "6px 0 6px" }}>{renderInline(ln.slice(2), onOpen, C, k)}</div>); }
    else if (/^\s*[-*]\s/.test(ln)) { (list = list || []).push(<li key={k} style={{ fontSize: 13, color: C.text, lineHeight: 1.6 }}>{renderInline(ln.replace(/^\s*[-*]\s/, ""), onOpen, C, k)}</li>); }
    else if (ln.trim() === "") { flush(); }
    else { flush(); blocks.push(<div key={k} style={{ fontSize: 13, color: C.text, lineHeight: 1.65, margin: "4px 0" }}>{renderInline(ln, onOpen, C, k)}</div>); }
  });
  flush();
  return <div>{blocks}</div>;
}

// ── Obsidian-style graph (hand-rolled SVG) ─────────────────────────────────────
function Graph({ notes, activeTitle, onOpen, C }) {
  const W = 640, H = 440, cx = W / 2, cy = H / 2, r = Math.min(W, H) / 2 - 60;
  const byTitle = useMemo(() => { const m = {}; notes.forEach(n => { m[n.title.toLowerCase()] = n; }); return m; }, [notes]);
  const pos = useMemo(() => {
    const p = {}; const n = notes.length || 1;
    notes.forEach((note, i) => { const a = (i / n) * Math.PI * 2 - Math.PI / 2; p[note.title] = { x: cx + r * Math.cos(a), y: cy + r * Math.sin(a) }; });
    return p;
  }, [notes]);
  const kindColor = k => k === "ops" ? C.gold : k === "doc" ? C.purple : C.teal;
  const edges = [];
  notes.forEach(n => (n.links || []).forEach(t => { const tgt = byTitle[(t || "").toLowerCase()]; if (tgt && pos[n.title] && pos[tgt.title]) edges.push([pos[n.title], pos[tgt.title], `${n.title}->${t}`]); }));
  return (
    <svg viewBox={`0 0 ${W} ${H}`} style={{ width: "100%", height: "auto", background: C.bg, borderRadius: 12, border: `0.5px solid ${C.border}` }}>
      {edges.map(([a, b, key]) => <line key={key} x1={a.x} y1={a.y} x2={b.x} y2={b.y} stroke={C.border2} strokeWidth={1} />)}
      {notes.map(n => {
        const p = pos[n.title]; if (!p) return null;
        const on = n.title === activeTitle;
        return (
          <g key={n.title} onClick={() => onOpen(n.title)} style={{ cursor: "pointer" }}>
            <circle cx={p.x} cy={p.y} r={on ? 9 : 6} fill={kindColor(n.kind)} stroke={on ? C.text : "transparent"} strokeWidth={1.5} />
            <text x={p.x} y={p.y - 12} textAnchor="middle" fontSize={10} fill={on ? C.text : C.muted} style={{ pointerEvents: "none" }}>{n.title}</text>
          </g>
        );
      })}
    </svg>
  );
}

